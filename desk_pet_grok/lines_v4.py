def angry_equivalent(category: str) -> str:
    """While she is angry every ordinary line is replaced by an angry one of the matching kind."""
    if category in ANGER_CATEGORIES:
        return category
    if category in ("click_reply", "rapid_clicks", "poke"):
        return "anger_poke"
    if category.startswith(("greet_", "festival_", "boot")):
        return "anger_greet"
    if category.startswith("work_"):
        return "anger_work"
    if category in ("pet_head", "pat_spoil"):
        return "anger_pat"
    return "anger_idle"
